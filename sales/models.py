import uuid as uuid_lib

from django.conf import settings
from django.db import models
from django.db.models import Q
from django.utils import timezone


class Shift(models.Model):
    """A cashier's drawer session: opening float, sales, and the counted cash at close."""

    client = models.ForeignKey("accounts.Client", on_delete=models.CASCADE, related_name="shifts")
    cashier = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="shifts")
    opened_at = models.DateTimeField(default=timezone.now)
    opening_float = models.DecimalField(max_digits=12, decimal_places=2, default=0)
    closed_at = models.DateTimeField(null=True, blank=True)
    expected_cash = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True)
    counted_cash = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True)
    note = models.CharField(max_length=200, blank=True)

    class Meta:
        ordering = ["-opened_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["cashier"], condition=Q(closed_at__isnull=True), name="one_open_shift_per_cashier"
            )
        ]

    @property
    def is_open(self) -> bool:
        return self.closed_at is None

    @property
    def variance(self):
        if self.counted_cash is None or self.expected_cash is None:
            return None
        return self.counted_cash - self.expected_cash

    def __str__(self):
        return f"Shift {self.pk} ({self.cashier})"


class Sale(models.Model):
    COMPLETED, VOIDED = "completed", "voided"
    STATUSES = [(COMPLETED, "Completed"), (VOIDED, "Voided")]

    client = models.ForeignKey("accounts.Client", on_delete=models.CASCADE, related_name="sales")
    # Generated by the till for each sale. Retrying the same sale can never record it twice.
    uuid = models.UUIDField(default=uuid_lib.uuid4)
    receipt_no = models.CharField(max_length=20)
    cashier = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="sales")
    shift = models.ForeignKey(Shift, null=True, blank=True, on_delete=models.PROTECT, related_name="sales")
    status = models.CharField(max_length=10, choices=STATUSES, default=COMPLETED)
    total = models.DecimalField(max_digits=12, decimal_places=2)
    vat_total = models.DecimalField(max_digits=12, decimal_places=2, default=0)
    cash_tendered = models.DecimalField(max_digits=12, decimal_places=2, default=0)
    change_given = models.DecimalField(max_digits=12, decimal_places=2, default=0)
    created_at = models.DateTimeField(default=timezone.now)
    voided_at = models.DateTimeField(null=True, blank=True)
    voided_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+"
    )
    void_reason = models.CharField(max_length=200, blank=True)

    class Meta:
        ordering = ["-created_at", "-id"]
        constraints = [
            models.UniqueConstraint(fields=["client", "uuid"], name="uniq_sale_uuid_per_client"),
            models.UniqueConstraint(fields=["client", "receipt_no"], name="uniq_receipt_no_per_client"),
        ]
        indexes = [models.Index(fields=["client", "-created_at"])]

    def __str__(self):
        return self.receipt_no


class SaleItem(models.Model):
    """Name, price and VAT are copied from the product at the time of sale."""

    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="items")
    product = models.ForeignKey("catalog.Product", on_delete=models.PROTECT, related_name="sale_items")
    name = models.CharField(max_length=200)
    barcode = models.CharField(max_length=64, blank=True)
    unit_price = models.DecimalField(max_digits=12, decimal_places=2)
    quantity = models.DecimalField(max_digits=12, decimal_places=3)
    vat_applies = models.BooleanField(default=True)
    vat_rate = models.DecimalField(max_digits=5, decimal_places=2, default=0)
    line_total = models.DecimalField(max_digits=12, decimal_places=2)
    vat_amount = models.DecimalField(max_digits=12, decimal_places=2, default=0)

    class Meta:
        ordering = ["id"]


class Payment(models.Model):
    CASH, MPESA, CARD, BANK = "cash", "mpesa", "card", "bank"
    METHOD_CHOICES = [(CASH, "Cash"), (MPESA, "M-Pesa"), (CARD, "Card"), (BANK, "Bank transfer")]
    METHODS = {code for code, _ in METHOD_CHOICES}

    client = models.ForeignKey("accounts.Client", on_delete=models.CASCADE, related_name="payments")
    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="payments")
    method = models.CharField(max_length=10, choices=METHOD_CHOICES)
    amount = models.DecimalField(max_digits=12, decimal_places=2)
    reference = models.CharField(max_length=40, blank=True)
    # M-Pesa codes are typed by the cashier and stay unverified until reconciled against the statement.
    is_verified = models.BooleanField(default=True)

    class Meta:
        ordering = ["id"]
        constraints = [
            models.UniqueConstraint(
                fields=["client", "reference"],
                condition=Q(method="mpesa") & ~Q(reference=""),
                name="uniq_mpesa_code_per_client",
            )
        ]
